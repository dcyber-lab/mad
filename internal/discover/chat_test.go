func TestPiChat(t *testing.T) {
	home := t.TempDir()
	t.Setenv("HOME", home)
	t.Setenv("PI_CODING_AGENT_DIR", "")
	dir := filepath.Join(home, ".pi", "agent", "sessions", "--r--")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(dir, "2026-10-29T10-00-00-000Z_sid-1.jsonl")
	if err := os.WriteFile(path, nil, 0o644); err != nil {
		t.Fatal(err)
	}
	c, ok := Conversation("pi")
	if !ok {
		t.Fatal("pi reads as no conversation")
	}
	if got := c.Transcripts("/r", "sid-1"); len(got) != 1 || got[0] != path {
		t.Errorf("Transcripts = %v", got)
	}
	if got := c.Transcripts("/r", "sid-2"); got != nil {
		t.Errorf("another session: %v", got)
	}

	lines := []string{
		`{"type":"session","version":3,"id":"s","cwd":"/r"}`,
		`{"type":"model_change","provider":"openai-codex","modelId":"gpt"}`,
		`{"type":"message","id":"a","message":{"role":"user","content":[{"type":"text","text":"list them"}],"timestamp":1}}`,
		`{"type":"message","id":"b","message":{"role":"assistant","content":[{"type":"thinking","thinking":"hm"},{"type":"toolCall","id":"call_1","name":"bash","arguments":{"command":"ls -la"}}],"timestamp":1785035561754}}`,
		`{"type":"message","id":"c","message":{"role":"toolResult","toolCallId":"call_1","toolName":"bash","content":[{"type":"text","text":"a.go"}],"isError":false,"timestamp":3}}`,
		`{"type":"message","id":"d","message":{"role":"assistant","content":[{"type":"text","text":"One **file**."}],"timestamp":1785035565582}}`,
		`{"type":"message","id":"e","message":{"role":"bashExecution","command":"git status","output":"clean","exitCode":0,"timestamp":5}}`,
		`{"type":"message","id":"f","message":{"role":"user","content":"plain string","timestamp":6}}`,
	}
	var got []string
	for _, l := range lines {
		for _, e := range c.Chat([]byte(l)) {
			got = append(got, fmt.Sprintf("%s|%s|%s|%q|%s|%s", e.Kind, e.Tool, e.Label, e.Text, e.ID, e.Msg))
		}
	}
	want := []string{
		`user|||"list them"||`,
		`other|||""||1785035561754`,
		`tool|bash|ls -la|""|call_1|1785035561754`,
		`result|||"a.go"|call_1|`,
		`text|||"One **file**."||1785035565582`,
		`command||! git status|""||`,
		`result|||"clean"||`,
		`user|||"plain string"||`,
	}
	if strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Errorf("Chat:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
}

// A call's Args are its input as JSON, long strings cut: what the window
// draws a diff or a todo list from.
func TestToolArgs(t *testing.T) {
	long := strings.Repeat("x", maxArg+10)
	line := `{"type":"assistant","message":{"id":"m","content":[{"type":"tool_use","id":"t","name":"Write","input":{"file_path":"/r/a.go","content":"` + long + `","n":3}}]}}`
	e := (claude{}).Chat([]byte(line))[0]
	var args struct {
		FilePath string `json:"file_path"`
		Content  string `json:"content"`
		N        int    `json:"n"`
	}
	if err := json.Unmarshal(e.Args, &args); err != nil {
		t.Fatalf("Args %s: %v", e.Args, err)
	}
	if args.FilePath != "/r/a.go" || args.N != 3 || !strings.HasPrefix(args.Content, "xxx") || !strings.HasSuffix(args.Content, "10 more bytes") {
		t.Errorf("Args = %+v", args)
	}

	patch := `{"type":"response_item","payload":{"type":"custom_tool_call","name":"apply_patch","call_id":"c","input":"*** Begin Patch\n*** Update File: a.go\n-a\n+b\n*** End Patch"}}`
	e = (codex{}).Chat([]byte(patch))[0]
	if string(e.Args) != `{"input":"*** Begin Patch\n*** Update File: a.go\n-a\n+b\n*** End Patch"}` {
		t.Errorf("codex custom Args = %s", e.Args)
	}
	if e := (claude{}).Chat([]byte(`{"type":"assistant","message":{"id":"m","content":[{"type":"tool_use","id":"t","name":"X","input":{}}]}}`))[0]; e.Args != nil {
		t.Errorf("no input: Args = %s", e.Args)
	}
}

// Images in each kind's transcript: what the user sent, what a call gave
// back; a type said or told by the data's start.
func TestChatImages(t *testing.T) {
	const png, jpg = "iVBORw0KGgo", "/9j/4AAQ"
	cases := []struct {
		name string
		got  []Entry
		want string // kind:text:mime... per entry
	}{
		{"claude", (claude{}).Chat([]byte(`{"type":"user","message":{"content":[{"type":"text","text":"look"},{"type":"image","source":{"type":"base64","data":"` + jpg + `"}}]}}`)),
			"user:look:image/jpeg"},
		{"claude alone", (claude{}).Chat([]byte(`{"type":"user","message":{"content":[{"type":"image","source":{"type":"base64","media_type":"image/png","data":"` + png + `"}}]}}`)),
			"user::image/png"},
		{"claude result", (claude{}).Chat([]byte(`{"type":"user","message":{"content":[{"type":"tool_result","tool_use_id":"t","content":[{"type":"text","text":"shot"},{"type":"image","source":{"type":"base64","media_type":"image/png","data":"` + png + `"}}]}]}}`)),
			"result:shot:image/png"},
		{"codex", (codex{}).Chat([]byte(`{"type":"response_item","payload":{"type":"message","role":"user","content":[{"type":"input_text","text":"see this\n"},{"type":"input_text","text":"<image name=[Image #1] path=\"/tmp/x.png\">"},{"type":"input_image","image_url":"data:image/png;base64,` + png + `"},{"type":"input_text","text":"</image>"}]}}`)),
			"user:see this:image/png"},
		{"pi", (piChat{}).Chat([]byte(`{"type":"message","timestamp":"2026-10-30T00:00:00Z","message":{"role":"user","content":[{"type":"text","text":"and this"},{"type":"image","data":"` + png + `","mimeType":"image/png"}]}}`)),
			"user:and this:image/png"},
		{"pi result", (piChat{}).Chat([]byte(`{"type":"message","timestamp":"2026-10-30T00:00:00Z","message":{"role":"toolResult","toolCallId":"c","content":[{"type":"image","data":"` + jpg + `","mimeType":"image/jpeg"}]}}`)),
			"result::image/jpeg"},
	}
	for _, c := range cases {
		var got []string
		for _, e := range c.got {
			s := e.Kind + ":" + e.Text
			for _, img := range e.Images {
				s += ":" + img.Mime
				if img.Data == "" {
					s += "(no data)"
				}
			}
			got = append(got, s)
		}
		if strings.Join(got, " ") != c.want {
			t.Errorf("%s: %q, want %q", c.name, strings.Join(got, " "), c.want)
		}
	}
}
